// generate-module-details.mjs — code-generator for
// src/wordpress/get-wordpress-module-details.ts.
//
// Shared by build.js (full Docker rebuild) and build-tar-zst.mjs (re-container
// the committed minified ZIPs into tar.zst) so both emit an identical descriptor
// shape. Local minified versions ship as a solid `wp-<v>.tar.zst`; remote
// versions (trunk/nightly) stay a GitHub `master.zip`.

const slugify = (v) => v.replace(/[^a-zA-Z0-9_]/g, '_');

/**
 * @param {object}  params
 * @param {object}  params.versions               wp-versions.json (slug -> version), keys pre-sorted.
 * @param {object}  params.meta                   { [slug]: { size, sha256, fileCount } } for local tar.zst bundles.
 * @param {object}  params.remoteWordPressModules { [slug]: { url, size } } for remote (trunk) modules.
 * @param {string}  params.latestStableVersion    default wpVersion for the generated function.
 * @returns {string} TypeScript source.
 */
export function generateModuleDetailsSource({
	versions,
	meta,
	remoteWordPressModules,
	latestStableVersion,
}) {
	const remoteModuleSlugs = Object.keys(remoteWordPressModules);
	const localVersionSlugs = Object.keys(versions).filter(
		(version) => !remoteModuleSlugs.includes(version)
	);

	const imports = localVersionSlugs
		.map(
			(version) =>
				`// @ts-ignore
import url_${slugify(version)} from './wp-${version}.tar.zst?url';`
		)
		.join('\n');

	const localCase = (version) => {
		const m = meta[version] ?? {};
		return `
		case '${version}':
			/** @ts-ignore */
			return {
				format: 'tar.zst',
				container: 'tar',
				codec: 'zstd',
				size: ${JSON.stringify(m.size ?? 0)},
				sha256: ${JSON.stringify(m.sha256 ?? '')},
				fileCount: ${JSON.stringify(m.fileCount ?? 0)},
				url: url_${slugify(version)},
			};
			`;
	};

	const remoteCase = (version) => `
		case '${version}':
			return {
				format: 'zip',
				size: ${JSON.stringify(remoteWordPressModules[version].size ?? 0)},
				url: ${JSON.stringify(remoteWordPressModules[version].url)},
			};
			`;

	const cases = Object.keys(versions)
		.map((version) =>
			remoteModuleSlugs.includes(version)
				? remoteCase(version)
				: localCase(version)
		)
		.join('');

	const nightlyCase = remoteWordPressModules.trunk
		? `
		case 'nightly':
			return {
				format: 'zip',
				size: ${JSON.stringify(remoteWordPressModules.trunk.size ?? 0)},
				url: ${JSON.stringify(remoteWordPressModules.trunk.url)},
			};
		`
		: '';

	return `${imports}

/**
 * This file was auto generated by packages/playground/wordpress-builds/build/build.js
 * and packages/playground/wordpress-builds/build/build-tar-zst.mjs
 * DO NOT CHANGE MANUALLY!
 * This file must statically exists in the project because of the way
 * vite resolves imports.
 */
export interface WordPressModuleDetails {
	/** Bundle container/codec. 'tar.zst' = solid zstd tar (streaming extract); 'zip' = per-entry DEFLATE. */
	format: 'tar.zst' | 'zip';
	/** Archive container, present for tar.zst bundles. */
	container?: 'tar';
	/** Compression codec, present for tar.zst bundles. */
	codec?: 'zstd';
	/** Compressed byte length of the bundle. */
	size: number;
	/** URL (or dev filesystem path) of the bundle. */
	url: string;
	/** SHA-256 of the compressed bundle, present for local tar.zst bundles. */
	sha256?: string;
	/** Number of regular files in the bundle, used for streaming-extract parity. */
	fileCount?: number;
}

export function getWordPressModuleDetails(
	wpVersion: string = ${JSON.stringify(latestStableVersion)}
): WordPressModuleDetails {
	switch (wpVersion) {
		${cases}${nightlyCase}
	}
	throw new Error('Unsupported WordPress module: ' + wpVersion);
}
`;
}
